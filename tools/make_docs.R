#' First sentence of the header comment of a file of R/ ("# R/<layer>/<file>.R -- purpose ...").
header_purpose <- function(file) {
  lines <- readLines(file.path("R", file), n = 12)[-1]
  continuation <- character()
  for (line in lines[-1]) { if (!grepl("^# [^ ]", line)) break; continuation <- c(continuation, sub("^# ", "", line)) }
  text <- paste(c(sub("^# R/[^ ]+ -- ", "", lines[1]), continuation), collapse = " ")
  sentence <- regmatches(text, regexpr("^.*?[.?](?=\\s|$)", text, perl = TRUE))
  sub("[.:]$", "", if (length(sentence)) sentence else text)
}
layer_text <- c(core = "helpers every other file may use", model = "the model, its fits and the simulator", signals = "what is computed from RR series and states",
                steps = "the per-recording steps of each analysis script", report = "notation, plots, figures and manuscript text")
index_section <- c("## 2. Where the functions are (`R/`)", "",
                   "`R/load.R` loads the layers in this order; a layer may use the layers before it.", "")
for (layer in PROJECT_LAYERS) {
  index_section <- c(index_section, sprintf("### `R/%s/`: %s", layer, layer_text[[layer]]), "")
  for (file in sort(list.files(file.path("R", layer)))) {
    code <- readLines(file.path("R", layer, file))
    functions <- sub("^([A-Za-z_.][A-Za-z0-9_.]*)\\s*<-\\s*function.*", "\\1", grep("^[A-Za-z_.][A-Za-z0-9_.]*\\s*<-\\s*function", code, value = TRUE))
    functions <- functions[!startsWith(functions, ".")]
    index_section <- c(index_section, sprintf("**`%s`**: %s  ", file.path(layer, file), header_purpose(file.path(layer, file))), fence(functions), "")
  }
}

