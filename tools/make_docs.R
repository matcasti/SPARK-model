  "| # | Script (`analysis/`) | Reads | Writes (`results/`) | Used in |", "|---:|:---|:---|:---|:---|",
  vapply(PIPELINE, function(s) sprintf("| %s | `%s` | %s | %s | %s |", s$id, basename(s$script), reads_cell(s),
