source("pipeline.R"); source("R/load.R")

fence <- function(x) paste0("`", x, "`", collapse = ", ")
results_cell <- function(step) fence(c(step$writes, sub("^\\{results\\}/", "", step$files)))
reads_cell <- function(step) {
  if (identical(step$reads, "*")) return("every `results/*.rds` that exists")
  parts <- c(if ("data" %in% step$reads) "CSV recordings (`data/`)", if (length(pipeline_reads(step))) paste0("`", step$reads[step$reads != "data"], "`"))
  if (length(parts)) paste(parts, collapse = ", ") else "(simulated)"
}

